package model;

public class Tarea {

    private String cuerpo;
    private String titulo;

    public Tarea(String cuerpo, String titulo) {
        this.cuerpo = cuerpo;
        this.titulo = titulo;
    }

    public String getCuerpo() {
        return cuerpo;
    }

    public String getTitulo() {
        return titulo;
    }




}
