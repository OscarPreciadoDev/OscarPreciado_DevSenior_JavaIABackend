/*
Requisitos Funcionales
1. Un campo de texto donde el usuario escribe una tarea nueva
2. Un botón "Agregar" que toma el texto del campo y lo agrega a una lista visible en pantalla.
3. Después de agregar, el campo de texto debe quedar vacío (listo para la siguiente tarea).
4. Un botón "Eliminar seleccionada" que borra la lista la tarea que el usuario haya seleccionado con el mouse
5. Un contador en algún lugar de la ventana (Una JLabel) que muestre cuantas tareas hay en total, y que se actualize cada que agregas o eliminas

Restricciones a propósito
1. No agregar una tarea si el campo de texto está vacío, debe mostrar algún tipo de aviso.
 */